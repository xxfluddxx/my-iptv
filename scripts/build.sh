#!/usr/bin/env bash
# Build your custom Bliss OS ISO.
#
#   ./scripts/build.sh               stage your customizations, then build the ISO
#   ./scripts/build.sh --stage-only  only copy/patch the files (no compile), for checking
#
# What it does:
#   1. Copies vendor/myiptv, your APKs and branding into $SRC_DIR/vendor/myiptv
#   2. Generates the settings files from box.conf
#   3. Hooks vendor/myiptv/myiptv.mk into Bliss's device/generic/common/device.mk
#   4. Runs lunch + make iso_img
set -euo pipefail
. "$(dirname "$0")/common.sh"
load_config

STAGE_ONLY=false
[ "${1:-}" = "--stage-only" ] && STAGE_ONLY=true

command -v rsync >/dev/null 2>&1 || die "rsync is missing. Run ./scripts/setup-host.sh first."
[ -d "$SRC_DIR/device/generic/common" ] || die "Bliss source not found in $SRC_DIR. Run ./scripts/sync.sh first."

DEST="$SRC_DIR/vendor/myiptv"
DEVICE_MK="$SRC_DIR/device/generic/common/device.mk"
HOOK_LINE='$(call inherit-product-if-exists, vendor/myiptv/myiptv.mk)'

# ---- 1. Stage files -----------------------------------------------------------
info "Staging customizations into $DEST"
mkdir -p "$DEST"
rsync -a --delete --exclude 'user_app/*.apk' "$REPO_ROOT/vendor/myiptv/" "$DEST/"
rm -f "$DEST"/user_app/*.apk

shopt -s nullglob
apks=("$REPO_ROOT"/apps/user/*.apk)
for apk in "${apks[@]}"; do
    # Module names come from file names: keep them simple.
    name="$(basename "$apk" .apk | tr -c '[:alnum:]_.\n-' '_')"
    cp "$apk" "$DEST/user_app/$name.apk"
done
info "  ${#apks[@]} app(s) from apps/user/ will be installed on first boot"

rm -f "$DEST/bootanimation.zip"
if [ -f "$REPO_ROOT/branding/bootanimation.zip" ]; then
    cp "$REPO_ROOT/branding/bootanimation.zip" "$DEST/bootanimation.zip"
    info "  custom boot animation: branding/bootanimation.zip"
fi
shopt -u nullglob

# ---- 2. Generate settings -----------------------------------------------------
info "Generating settings from $(basename "$CONFIG_FILE")"
{
    echo "# GENERATED by my-iptv/scripts/build.sh from box.conf. Do not edit."
    echo "MYIPTV_LEANBACK := $ADVERTISE_LEANBACK"
    echo "PRODUCT_PRODUCT_PROPERTIES += ro.myiptv.version=$(printf '%s' "$BOX_VERSION" | tr -c '[:alnum:]._-' '_')"
    [ "$DISABLE_TASKBAR" = "true" ] && echo "PRODUCT_PRODUCT_PROPERTIES += persist.bliss.disable_taskbar=true"
    [ "$DISABLE_SETUP_WIZARD" = "true" ] && echo "PRODUCT_PRODUCT_PROPERTIES += ro.setupwizard.mode=DISABLED"
    [ -n "${TIMEZONE:-}" ] && echo "PRODUCT_PRODUCT_PROPERTIES += persist.sys.timezone=$TIMEZONE"
} > "$DEST/generated.mk"

{
    echo "# GENERATED by my-iptv/scripts/build.sh from box.conf. Do not edit."
    echo "MYIPTV_DEVICE_NAME=$(shell_quote "$BOX_NAME")"
    echo "MYIPTV_DEFAULT_LAUNCHER=$(shell_quote "${DEFAULT_LAUNCHER:-}")"
    echo "MYIPTV_SCREEN_NEVER_OFF=$(shell_quote "$SCREEN_NEVER_OFF")"
    echo "MYIPTV_DISABLE_PACKAGES=$(shell_quote "${DISABLE_PACKAGES:-}")"
} > "$DEST/myiptv.conf"

# ---- 3. Hook into Bliss -------------------------------------------------------
if ! grep -qF "$HOOK_LINE" "$DEVICE_MK"; then
    info "Hooking vendor/myiptv into device/generic/common/device.mk"
    printf '\n# my-iptv customizations (added by my-iptv/scripts/build.sh)\n%s\n' "$HOOK_LINE" >> "$DEVICE_MK"
fi

BLISS_USER_APP_DIR="$SRC_DIR/device/generic/common/user_app"
if [ "$REMOVE_BLISS_USER_APPS" = "true" ] && [ -d "$BLISS_USER_APP_DIR" ]; then
    mkdir -p "$BLISS_USER_APP_DIR/removed-by-myiptv"
    find "$BLISS_USER_APP_DIR" -maxdepth 1 -name '*.apk' -exec mv -f {} "$BLISS_USER_APP_DIR/removed-by-myiptv/" \;
    info "Removed Bliss's bundled extra apps (restored automatically by sync.sh)"
fi

if [ "$USE_WIDEVINE" = "true" ] && [ ! -d "$SRC_DIR/vendor/google/proprietary/widevine-prebuilt" ]; then
    info "Fetching prebuilt Widevine"
    git clone --depth 1 https://github.com/supremegamers/vendor_google_proprietary_widevine-prebuilt \
        "$SRC_DIR/vendor/google/proprietary/widevine-prebuilt"
fi

if $STAGE_ONLY; then
    info "Stage-only: done. Lunch target would be $LUNCH_TARGET"
    exit 0
fi

# ---- 4. Build ----------------------------------------------------------------
export BLISS_BUILD_VARIANT USE_WIDEVINE
export BLISS_SPECIAL_VARIANT="-$BOX_SLUG"
[ -f "$HOME/.cargo/env" ] && . "$HOME/.cargo/env"

cd "$SRC_DIR"
info "Building $LUNCH_TARGET ($BLISS_BUILD_VARIANT) with $JOBS jobs. Expect 1-4 hours on the first build."
# envsetup.sh/lunch are not written for 'set -eu'
set +eu
. build/envsetup.sh
lunch "$LUNCH_TARGET" || die "lunch $LUNCH_TARGET failed"
make -j"$JOBS" iso_img || die "Build failed. Scroll up for the first 'error:' line."
set -eu

iso="$(ls -t out/target/product/*/*.iso 2>/dev/null | head -1 || true)"
[ -n "$iso" ] || die "Build finished but no .iso found under out/target/product/"
info "Done! Your image: $SRC_DIR/$iso"
echo "    Flash it to a USB stick with Rufus or balenaEtcher and boot the Beelink (F7 = boot menu)."
